function normalizeRequiredText(
  value:
    unknown,
): string | null {
  if (
    typeof value !==
      "string"
  ) {
    return null;
  }

  const normalized =
    value.trim();

  return normalized
    ? normalized
    : null;
}

function normalizeDate(
  value:
    unknown,
): string | null {
  const normalized =
    normalizeRequiredText(
      value,
    );

  if (
    !normalized ||
    !/^\d{4}-\d{2}-\d{2}$/.test(
      normalized,
    )
  ) {
    return null;
  }

  const date =
    new Date(
      `${normalized}T00:00:00.000Z`,
    );

  if (
    Number.isNaN(
      date.getTime(),
    )
  ) {
    return null;
  }

  return date
    .toISOString()
    .slice(
      0,
      10,
    ) ===
    normalized
    ? normalized
    : null;
}

function readBoolean(
  value:
    Json | undefined,
  fallback:
    boolean,
): boolean {
  return typeof value ===
    "boolean"
    ? value
    : fallback;
}

function cloneDefaultFilters():
  FinancialCalendarPersistentFilters {
  return {
    search:
      DEFAULT_FILTERS.search,

    eventTypes:
      [
        ...DEFAULT_FILTERS.eventTypes,
      ],

    statuses:
      [
        ...DEFAULT_FILTERS.statuses,
      ],

    priorities:
      [
        ...DEFAULT_FILTERS.priorities,
      ],

    accountIds:
      [
        ...DEFAULT_FILTERS.accountIds,
      ],

    includeCompleted:
      DEFAULT_FILTERS.includeCompleted,

    includeCanceled:
      DEFAULT_FILTERS.includeCanceled,

    includeAutoGenerated:
      DEFAULT_FILTERS.includeAutoGenerated,

    includeManual:
      DEFAULT_FILTERS.includeManual,
  };
}

function isRecord(
  value:
    unknown,
): value is Record<string, Json | undefined> {
  return Boolean(
    value &&
    typeof value ===
      "object" &&
    !Array.isArray(
      value,
    ),
  );
}

function getCalendarFeatureAccessMessage({
  reason,
  requiredPlan,
}: {
  reason:
    | "allowed"
    | "requires-plus"
    | "requires-pro"
    | "inactive-subscription";

  requiredPlan:
    | "free"
    | "plus"
    | "pro"
    | null;
}) {
  switch (
    reason
  ) {
    case "inactive-subscription":
      return "Calendar is unavailable because this workspace subscription is inactive. Please reactivate the subscription to continue.";

    case "requires-pro":
      return "Calendar requires the CASE Budget Pro plan for this workspace.";

    case "requires-plus":
      return "Calendar requires the CASE Budget Plus plan or higher for this workspace.";

    case "allowed":
    default: {
      if (
        requiredPlan ===
        "pro"
      ) {
        return "Calendar requires the CASE Budget Pro plan for this workspace.";
      }

      if (
        requiredPlan ===
        "plus"
      ) {
        return "Calendar requires the CASE Budget Plus plan or higher for this workspace.";
      }

      return "Calendar is not available for the current workspace subscription.";
    }
  }
}

function failure(
  message:
    string,
): GetFinancialCalendarPreferencesResult {
  return {
    success:
      false,

    error:
      message,
  };
}
