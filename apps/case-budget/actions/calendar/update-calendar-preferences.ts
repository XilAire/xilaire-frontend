function parsePersistentFiltersJson(
  value:
    Json,
): FinancialCalendarPersistentFilters | null {
  if (
    !isRecord(
      value,
    )
  ) {
    return null;
  }

  const eventTypes =
    parseEventTypesJson(
      value.eventTypes,
    );

  const statuses =
    parseStatusesJson(
      value.statuses,
    );

  const priorities =
    parsePrioritiesJson(
      value.priorities,
    );

  const accountIds =
    parseStringArrayJson(
      value.accountIds,
    );

  if (
    eventTypes ===
      null ||
    statuses ===
      null ||
    priorities ===
      null ||
    accountIds ===
      null
  ) {
    return null;
  }

  return {
    search:
      typeof value.search ===
        "string"
        ? value.search
        : "",

    eventTypes,

    statuses,

    priorities,

    accountIds,

    includeCompleted:
      readBoolean(
        value.includeCompleted,
        DEFAULT_FILTERS.includeCompleted,
      ),

    includeCanceled:
      readBoolean(
        value.includeCanceled,
        DEFAULT_FILTERS.includeCanceled,
      ),

    includeAutoGenerated:
      readBoolean(
        value.includeAutoGenerated,
        DEFAULT_FILTERS.includeAutoGenerated,
      ),

    includeManual:
      readBoolean(
        value.includeManual,
        DEFAULT_FILTERS.includeManual,
      ),
  };
}

