export function normalizeCalendarDate(
  value: string | Date,
) {
  if (
    value instanceof
    Date
  ) {
    return formatDateKey(
      value,
    );
  }

  const normalizedValue =
    value.slice(
      0,
      10,
    );

  const date =
    parseDateKey(
      normalizedValue,
    );

  if (
    Number.isNaN(
      date.getTime(),
    )
  ) {
    return formatDateKey(
      new Date(),
    );
  }

  return normalizedValue;
}

export function parseDateKey(
  value: string,
) {
  const [
    year,
    month,
    day,
  ] =
    value
      .slice(
        0,
        10,
      )
      .split(
        "-",
      )
      .map(
        Number,
      );

  if (
    !Number.isInteger(
      year,
    ) ||
    !Number.isInteger(
      month,
    ) ||
    !Number.isInteger(
      day,
    )
  ) {
    return new Date(
      Number.NaN,
    );
  }

  return new Date(
    year,
    month -
      1,
    day,
  );
}

export function formatDateKey(
  value: Date,
) {
  const year =
    value.getFullYear();

  const month =
    String(
      value.getMonth() +
        1,
    ).padStart(
      2,
      "0",
    );

  const day =
    String(
      value.getDate(),
    ).padStart(
      2,
      "0",
    );

  return `${year}-${month}-${day}`;
}

export function addCalendarDays(
  value: string,
  amount: number,
) {
  const date =
    parseDateKey(
      value,
    );

  date.setDate(
    date.getDate() +
      amount,
  );

  return formatDateKey(
    date,
  );
}

export function addCalendarWeeks(
  value: string,
  amount: number,
) {
  return addCalendarDays(
    value,
    amount *
      7,
  );
}

export function addCalendarMonths(
  value: string,
  amount: number,
) {
  const date =
    parseDateKey(
      value,
    );

  const originalDay =
    date.getDate();

  date.setDate(
    1,
  );

  date.setMonth(
    date.getMonth() +
      amount,
  );

  const lastDay =
    getLastDayOfMonth(
      date.getFullYear(),
      date.getMonth() +
        1,
    );

  date.setDate(
    Math.min(
      originalDay,
      lastDay,
    ),
  );

  return formatDateKey(
    date,
  );
}

export function addCalendarYears(
  value: string,
  amount: number,
) {
  const date =
    parseDateKey(
      value,
    );

  const month =
    date.getMonth();

  const day =
    date.getDate();

  date.setDate(
    1,
  );

  date.setFullYear(
    date.getFullYear() +
      amount,
  );

  date.setMonth(
    month,
  );

  date.setDate(
    Math.min(
      day,
      getLastDayOfMonth(
        date.getFullYear(),
        month +
          1,
      ),
    ),
  );

  return formatDateKey(
    date,
  );
}

export function differenceInCalendarDays(
  startDate: string,
  endDate: string,
) {
  const start =
    parseDateKey(
      startDate,
    );

  const end =
    parseDateKey(
      endDate,
    );

  return Math.round(
    (
      end.getTime() -
      start.getTime()
    ) /
      MILLISECONDS_PER_DAY,
  );
}

export function compareCalendarDates(
  firstDate: string,
  secondDate: string,
) {
  return normalizeCalendarDate(
    firstDate,
  ).localeCompare(
    normalizeCalendarDate(
      secondDate,
    ),
  );
}

export function isDateWithinRange(
  date: string,
  range:
    FinancialCalendarDateRange,
) {
  const normalizedDate =
    normalizeCalendarDate(
      date,
    );

  return (
    normalizedDate >=
      normalizeCalendarDate(
        range.startDate,
      ) &&
    normalizedDate <=
      normalizeCalendarDate(
        range.endDate,
      )
  );
}

export function getStartOfWeek(
  value: string,
  weekStartsOn:
    FinancialCalendarWeekday = 0,
) {
  const date =
    parseDateKey(
      value,
    );

  const day =
    date.getDay();

  const difference =
    (
      day -
      weekStartsOn +
      7
    ) %
    7;

  date.setDate(
    date.getDate() -
      difference,
  );

  return formatDateKey(
    date,
  );
}

export function getEndOfWeek(
  value: string,
  weekStartsOn:
    FinancialCalendarWeekday = 0,
) {
  return addCalendarDays(
    getStartOfWeek(
      value,
      weekStartsOn,
    ),
    6,
  );
}

export function getStartOfMonth(
  value: string,
) {
  const date =
    parseDateKey(
      value,
    );

  return formatDateKey(
    new Date(
      date.getFullYear(),
      date.getMonth(),
      1,
    ),
  );
}

export function getEndOfMonth(
  value: string,
) {
  const date =
    parseDateKey(
      value,
    );

  return formatDateKey(
    new Date(
      date.getFullYear(),
      date.getMonth() +
        1,
      0,
    ),
  );
}

export function getCalendarVisibleRange({
  selectedDate,
  view,
  weekStartsOn,
}: {
  selectedDate: string;
  view:
    FinancialCalendarView;
  weekStartsOn:
    FinancialCalendarWeekday;
}): FinancialCalendarDateRange {
  if (
    view ===
    "week"
  ) {
    return {
      startDate:
        getStartOfWeek(
          selectedDate,
          weekStartsOn,
        ),
      endDate:
        getEndOfWeek(
          selectedDate,
          weekStartsOn,
        ),
    };
  }

  if (
    view ===
    "agenda"
  ) {
    return {
      startDate:
        selectedDate,
      endDate:
        addCalendarDays(
          selectedDate,
          30,
        ),
    };
  }

  const monthStart =
    getStartOfMonth(
      selectedDate,
    );

  const monthEnd =
    getEndOfMonth(
      selectedDate,
    );

  return {
    startDate:
      getStartOfWeek(
        monthStart,
        weekStartsOn,
      ),
    endDate:
      getEndOfWeek(
        monthEnd,
        weekStartsOn,
      ),
  };
}

export function buildCalendarMonth({
  selectedDate,
  occurrences,
  weekStartsOn = 0,
  showWeekends = true,
  today = formatDateKey(
    new Date(),
  ),
}: {
  selectedDate: string;
  occurrences:
    FinancialCalendarEventOccurrence[];
  weekStartsOn?:
    FinancialCalendarWeekday;
  showWeekends?: boolean;
  today?: string;
}): FinancialCalendarMonth {
  const normalizedSelectedDate =
    normalizeCalendarDate(
      selectedDate,
    );

  const selectedDateObject =
    parseDateKey(
      normalizedSelectedDate,
    );

  const month =
    selectedDateObject.getMonth() +
    1;

  const year =
    selectedDateObject.getFullYear();

  const monthStart =
    getStartOfMonth(
      normalizedSelectedDate,
    );

  const monthEnd =
    getEndOfMonth(
      normalizedSelectedDate,
    );

  const visibleStart =
    getStartOfWeek(
      monthStart,
      weekStartsOn,
    );

  const visibleEnd =
    getEndOfWeek(
      monthEnd,
      weekStartsOn,
    );

  const days:
    FinancialCalendarDay[] = [];

  let currentDate =
    visibleStart;

  while (
    currentDate <=
    visibleEnd
  ) {
    const currentDateObject =
      parseDateKey(
        currentDate,
      );

    const isWeekend =
      currentDateObject.getDay() ===
        0 ||
      currentDateObject.getDay() ===
        6;

    if (
      showWeekends ||
      !isWeekend
    ) {
      days.push(
        buildCalendarDay({
          date:
            currentDate,
          selectedDate:
            normalizedSelectedDate,
          month,
          today,
          occurrences,
        }),
      );
    }

    currentDate =
      addCalendarDays(
        currentDate,
        1,
      );
  }

  const daysPerWeek =
    showWeekends
      ? 7
      : 5;

  const weeks:
    FinancialCalendarWeek[] = [];

  for (
    let index = 0;
    index <
    days.length;
    index +=
      daysPerWeek
  ) {
    const weekDays =
      days.slice(
        index,
        index +
          daysPerWeek,
      );

    if (
      weekDays.length ===
      0
    ) {
      continue;
    }

    weeks.push({
      id:
        `calendar-week-${weekDays[0].date}`,
      startDate:
        weekDays[0].date,
      endDate:
        weekDays[
          weekDays.length -
            1
        ].date,
      days:
        weekDays,
    });
  }

  return {
    month,
    year,
    startDate:
      visibleStart,
    endDate:
      visibleEnd,
    weeks,
  };
}

export function buildCalendarDay({
  date,
  selectedDate,
  month,
  today,
  occurrences,
}: {
  date: string;
  selectedDate: string;
  month: number;
  today: string;
  occurrences:
    FinancialCalendarEventOccurrence[];
}): FinancialCalendarDay {
  const matchingOccurrences =
    occurrences
      .filter(
        (
          occurrence,
        ) =>
          occurrence.date ===
          date,
      )
      .sort(
        compareCalendarOccurrences,
      );

  const dateObject =
    parseDateKey(
      date,
    );

  const financialTotals =
    calculateOccurrenceTotals(
      matchingOccurrences,
    );

  return {
    date,

    isCurrentMonth:
      dateObject.getMonth() +
        1 ===
      month,

    isToday:
      date ===
      today,

    isSelected:
      date ===
      selectedDate,

    isWeekend:
      dateObject.getDay() ===
        0 ||
      dateObject.getDay() ===
        6,

    occurrences:
      matchingOccurrences,

    totalScheduledAmount:
      normalizeCurrency(
        matchingOccurrences.reduce(
          (
            total,
            occurrence,
          ) =>
            total +
            Math.abs(
              occurrence.event.amount ??
                0,
            ),
          0,
        ),
      ),

    totalIncomeAmount:
      financialTotals.income,

    totalExpenseAmount:
      financialTotals.expense,

    dueCount:
      matchingOccurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.status ===
          "due",
      ).length,

    pastDueCount:
      matchingOccurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.status ===
          "past-due",
      ).length,

    completedCount:
      matchingOccurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.status ===
          "completed",
      ).length,
  };
}

export function buildAgendaGroups(
  occurrences:
    FinancialCalendarEventOccurrence[],
): FinancialCalendarAgendaGroup[] {
  const groupedOccurrences =
    occurrences.reduce<
      Record<
        string,
        FinancialCalendarEventOccurrence[]
      >
    >(
      (
        groups,
        occurrence,
      ) => {
        const existingGroup =
          groups[
            occurrence.date
          ] ??
          [];

        return {
          ...groups,
          [occurrence.date]: [
            ...existingGroup,
            occurrence,
          ],
        };
      },
      {},
    );

  return Object.entries(
    groupedOccurrences,
  )
    .sort(
      (
        [
          firstDate,
        ],
        [
          secondDate,
        ],
      ) =>
        firstDate.localeCompare(
          secondDate,
        ),
    )
    .map(
      (
        [
          date,
          dateOccurrences,
        ],
      ) => {
        const sortedOccurrences =
          [
            ...dateOccurrences,
          ].sort(
            compareCalendarOccurrences,
          );

        const totals =
          calculateOccurrenceTotals(
            sortedOccurrences,
          );

        return {
          date,
          label:
            formatAgendaDateLabel(
              date,
            ),
          occurrences:
            sortedOccurrences,
          totalIncomeAmount:
            totals.income,
          totalExpenseAmount:
            totals.expense,
        };
      },
    );
}

export function filterCalendarEvents(
  events:
    FinancialCalendarEvent[],
  filters:
    FinancialCalendarFilters,
) {
  const normalizedSearch =
    filters.search
      .trim()
      .toLowerCase();

  return events.filter(
    (
      event,
    ) => {
      if (
        normalizedSearch
      ) {
        const searchableValue = [
          event.title,
          event.description,
          event.notes,
          event.type,
          event.status,
        ]
          .filter(
            Boolean,
          )
          .join(
            " ",
          )
          .toLowerCase();

        if (
          !searchableValue.includes(
            normalizedSearch,
          )
        ) {
          return false;
        }
      }

      if (
        filters.eventTypes.length >
          0 &&
        !filters.eventTypes.includes(
          event.type,
        )
      ) {
        return false;
      }

      if (
        filters.statuses.length >
          0 &&
        !filters.statuses.includes(
          event.status,
        )
      ) {
        return false;
      }

      if (
        filters.priorities.length >
          0 &&
        !filters.priorities.includes(
          event.priority,
        )
      ) {
        return false;
      }

      if (
        filters.accountIds.length >
          0 &&
        (
          !event.accountId ||
          !filters.accountIds.includes(
            event.accountId,
          )
        )
      ) {
        return false;
      }

      if (
        !filters.includeCompleted &&
        event.status ===
          "completed"
      ) {
        return false;
      }

      if (
        !filters.includeCanceled &&
        event.status ===
          "canceled"
      ) {
        return false;
      }

      if (
        !filters.includeAutoGenerated &&
        event.isAutoGenerated
      ) {
        return false;
      }

      if (
        !filters.includeManual &&
        !event.isAutoGenerated
      ) {
        return false;
      }

      return true;
    },
  );
}

export function applyCalendarPreferences(
  events:
    FinancialCalendarEvent[],
  preferences:
    FinancialCalendarPreferences,
) {
  return events.filter(
    (
      event,
    ) => {
      if (
        event.status ===
          "completed" &&
        !preferences.showCompletedEvents
      ) {
        return false;
      }

      if (
        event.status ===
          "canceled" &&
        !preferences.showCanceledEvents
      ) {
        return false;
      }

      switch (
        event.type
      ) {
        case "bill":
          return preferences.showBills;

        case "paycheck":
        case "income":
          return preferences.showPaychecks;

        case "transaction":
          return preferences.showTransactions;

        case "savings-contribution":
          return preferences.showSavingsContributions;

        case "debt-payment":
          return preferences.showDebtPayments;

        case "transfer":
          return preferences.showTransfers;

        case "reminder":
          return preferences.showReminders;

        case "custom":
        default:
          return preferences.showCustomEvents;
      }
    },
  );
}

export function generateCalendarOccurrences({
  events,
  range,
  today = formatDateKey(
    new Date(),
  ),
}: {
  events:
    FinancialCalendarEvent[];
  range:
    FinancialCalendarDateRange;
  today?: string;
}) {
  return events
    .flatMap(
      (
        event,
      ) =>
        generateEventOccurrences({
          event,
          range,
          today,
        }),
    )
    .sort(
      compareCalendarOccurrences,
    );
}

export function generateEventOccurrences({
  event,
  range,
  today,
}: {
  event:
    FinancialCalendarEvent;
  range:
    FinancialCalendarDateRange;
  today: string;
}): FinancialCalendarEventOccurrence[] {
  if (
    !event.recurrence
  ) {
    if (
      !isDateWithinRange(
        event.date,
        range,
      )
    ) {
      return [];
    }

    return [
      createOccurrence({
        event,
        date:
          event.date,
        today,
        isRecurringOccurrence:
          false,
      }),
    ];
  }

  const occurrenceDates =
    generateRecurringDates({
      startDate:
        event.date,
      recurrence:
        event.recurrence,
      range,
    });

  return occurrenceDates.map(
    (
      date,
    ) =>
      createOccurrence({
        event,
        date,
        today,
        isRecurringOccurrence:
          true,
      }),
  );
}

export function generateRecurringDates({
  startDate,
  recurrence,
  range,
}: {
  startDate: string;
  recurrence:
    FinancialCalendarRecurrenceRule;
  range:
    FinancialCalendarDateRange;
}) {
  const normalizedStartDate =
    normalizeCalendarDate(
      startDate,
    );

  const normalizedRange:
    FinancialCalendarDateRange = {
      startDate:
        normalizeCalendarDate(
          range.startDate,
        ),
      endDate:
        normalizeCalendarDate(
          range.endDate,
        ),
    };

  const dates:
    string[] = [];

  const maximumOccurrences =
    recurrence.endType ===
      "occurrences"
      ? Math.max(
          0,
          recurrence.occurrenceCount ??
            0,
        )
      : Number.POSITIVE_INFINITY;

  const recurrenceEndDate =
    recurrence.endType ===
      "date"
      ? recurrence.endDate
      : undefined;

  let generatedCount =
    0;

  let safetyCount =
    0;

  let currentDate =
    normalizedStartDate;

  while (
    currentDate <=
      normalizedRange.endDate &&
    generatedCount <
      maximumOccurrences &&
    safetyCount <
      5000
  ) {
    safetyCount +=
      1;

    const candidateDates =
      resolveRecurrenceCandidateDates({
        currentDate,
        startDate:
          normalizedStartDate,
        recurrence,
      });

    for (
      const candidateDate of
      candidateDates
    ) {
      if (
        candidateDate <
        normalizedStartDate
      ) {
        continue;
      }

      if (
        recurrenceEndDate &&
        candidateDate >
          recurrenceEndDate
      ) {
        return dates;
      }

      if (
        generatedCount >=
        maximumOccurrences
      ) {
        return dates;
      }

      generatedCount +=
        1;

      if (
        isDateWithinRange(
          candidateDate,
          normalizedRange,
        )
      ) {
        dates.push(
          candidateDate,
        );
      }
    }

    currentDate =
      getNextRecurrenceAnchor({
        currentDate,
        recurrence,
      });

    if (
      recurrenceEndDate &&
      currentDate >
        recurrenceEndDate
    ) {
      break;
    }
  }

  return Array.from(
    new Set(
      dates,
    ),
  ).sort();
}

export function calculateCalendarSummary({
  occurrences,
  today = formatDateKey(
    new Date(),
  ),
}: {
  occurrences:
    FinancialCalendarEventOccurrence[];
  today?: string;
}): FinancialCalendarSummary {
  const upcomingOccurrences =
    occurrences.filter(
      (
        occurrence,
      ) =>
        occurrence.date >=
          today &&
        occurrence.status !==
          "completed" &&
        occurrence.status !==
          "canceled",
    );

  const totals =
    calculateOccurrenceTotals(
      occurrences,
    );

  const nextEvent =
    upcomingOccurrences[
      0
    ];

  const nextPaycheck =
    upcomingOccurrences.find(
      (
        occurrence,
      ) =>
        occurrence.event.type ===
          "paycheck" ||
        occurrence.event.type ===
          "income",
    );

  const nextBill =
    upcomingOccurrences.find(
      (
        occurrence,
      ) =>
        occurrence.event.type ===
        "bill",
    );

  return {
    totalEventCount:
      occurrences.length,

    upcomingEventCount:
      upcomingOccurrences.length,

    dueTodayCount:
      occurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.date ===
            today &&
          occurrence.status ===
            "due",
      ).length,

    pastDueCount:
      occurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.status ===
          "past-due",
      ).length,

    completedCount:
      occurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.status ===
          "completed",
      ).length,

    upcomingBillCount:
      upcomingOccurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.event.type ===
          "bill",
      ).length,

    upcomingPaycheckCount:
      upcomingOccurrences.filter(
        (
          occurrence,
        ) =>
          occurrence.event.type ===
            "paycheck" ||
          occurrence.event.type ===
            "income",
      ).length,

    scheduledIncomeAmount:
      totals.income,

    scheduledExpenseAmount:
      totals.expense,

    netScheduledCashFlow:
      normalizeCurrency(
        totals.income -
        totals.expense,
      ),

    nextEventDate:
      nextEvent?.date,

    nextPaycheckDate:
      nextPaycheck?.date,

    nextBillDueDate:
      nextBill?.date,
  };
}

export function detectCalendarConflicts({
  occurrences,
  accountBalances = {},
  today = formatDateKey(
    new Date(),
  ),
}: {
  occurrences:
    FinancialCalendarEventOccurrence[];
  accountBalances?:
    Record<
      string,
      number
    >;
  today?: string;
}): FinancialCalendarConflict[] {
  const conflicts:
    FinancialCalendarConflict[] = [];

  const groupedByDate =
    occurrences.reduce<
      Record<
        string,
        FinancialCalendarEventOccurrence[]
      >
    >(
      (
        groups,
        occurrence,
      ) => ({
        ...groups,
        [occurrence.date]: [
          ...(
            groups[
              occurrence.date
            ] ??
            []
          ),
          occurrence,
        ],
      }),
      {},
    );

  Object.entries(
    groupedByDate,
  ).forEach(
    (
      [
        date,
        dateOccurrences,
      ],
    ) => {
      const criticalBills =
        dateOccurrences.filter(
          (
            occurrence,
          ) =>
            occurrence.event.type ===
              "bill" &&
            occurrence.event.priority ===
              "critical" &&
            occurrence.status !==
              "completed" &&
            occurrence.status !==
              "canceled",
        );

      if (
        criticalBills.length >
        1
      ) {
        conflicts.push({
          id:
            `multiple-critical-bills-${date}`,
          type:
            "multiple-critical-bills",
          severity:
            "warning",
          title:
            "Multiple critical bills are due",
          description:
            `${criticalBills.length} critical bills are scheduled on the same date.`,
          date,
          eventIds:
            criticalBills.map(
              (
                occurrence,
              ) =>
                occurrence.eventId,
            ),
          amount:
            normalizeCurrency(
              criticalBills.reduce(
                (
                  total,
                  occurrence,
                ) =>
                  total +
                  Math.abs(
                    occurrence.event.amount ??
                      0,
                  ),
                0,
              ),
            ),
          actionLabel:
            "Review bills",
          actionHref:
            "/dashboard/bills",
        });
      }

      const autopayBills =
        dateOccurrences.filter(
          (
            occurrence,
          ) =>
            occurrence.event.type ===
              "bill" &&
            occurrence.event.description
              ?.toLowerCase()
              .includes(
                "autopay",
              ),
        );

      if (
        autopayBills.length >
        1
      ) {
        conflicts.push({
          id:
            `overlapping-autopay-${date}`,
          type:
            "overlapping-autopay",
          severity:
            "info",
          title:
            "Multiple autopay charges",
          description:
            `${autopayBills.length} automatic payments are scheduled for the same date.`,
          date,
          eventIds:
            autopayBills.map(
              (
                occurrence,
              ) =>
                occurrence.eventId,
            ),
          amount:
            normalizeCurrency(
              autopayBills.reduce(
                (
                  total,
                  occurrence,
                ) =>
                  total +
                  Math.abs(
                    occurrence.event.amount ??
                      0,
                  ),
                0,
              ),
            ),
          actionLabel:
            "Review autopay bills",
          actionHref:
            "/dashboard/bills",
        });
      }
    },
  );

  occurrences.forEach(
    (
      occurrence,
    ) => {
      if (
        occurrence.status ===
        "past-due"
      ) {
        conflicts.push({
          id:
            `past-due-${occurrence.id}`,
          type:
            "past-due",
          severity:
            occurrence.event.priority ===
            "critical"
              ? "critical"
              : "warning",
          title:
            `${occurrence.event.title} is past due`,
          description:
            "This event has passed its scheduled date and still requires attention.",
          date:
            occurrence.date,
          eventIds: [
            occurrence.eventId,
          ],
          amount:
            occurrence.event.amount,
          actionLabel:
            getOccurrenceActionLabel(
              occurrence,
            ),
          actionHref:
            getOccurrenceActionHref(
              occurrence,
            ),
        });
      }

      if (
        occurrence.event.type ===
          "bill" &&
        !occurrence.event.accountId
      ) {
        conflicts.push({
          id:
            `missing-account-${occurrence.id}`,
          type:
            "missing-account",
          severity:
            "info",
          title:
            `${occurrence.event.title} has no payment account`,
          description:
            "Select an account so CASE Budget can evaluate whether enough cash is available.",
          date:
            occurrence.date,
          eventIds: [
            occurrence.eventId,
          ],
          amount:
            occurrence.event.amount,
          actionLabel:
            "Review bill",
          actionHref:
            "/dashboard/bills",
        });
      }

      if (
        occurrence.event.type ===
          "bill" &&
        occurrence.event.accountId
      ) {
        const availableAmount =
          accountBalances[
            occurrence.event.accountId
          ];

        const requiredAmount =
          Math.abs(
            occurrence.event.amount ??
              0,
          );

        if (
          typeof availableAmount ===
            "number" &&
          requiredAmount >
            availableAmount
        ) {
          conflicts.push({
            id:
              `insufficient-funds-${occurrence.id}`,
            type:
              "insufficient-funds",
            severity:
              occurrence.event.priority ===
              "critical"
                ? "critical"
                : "warning",
            title:
              `Possible shortage for ${occurrence.event.title}`,
            description:
              "The selected account balance may not cover this scheduled payment.",
            date:
              occurrence.date,
            eventIds: [
              occurrence.eventId,
            ],
            amount:
              requiredAmount,
            availableAmount:
              normalizeCurrency(
                availableAmount,
              ),
            shortageAmount:
              normalizeCurrency(
                requiredAmount -
                availableAmount,
              ),
            actionLabel:
              "Review cash flow",
            actionHref:
              "/dashboard/pay-cycles",
          });
        }
      }

      if (
        occurrence.date <
          today &&
        occurrence.status ===
          "scheduled"
      ) {
        conflicts.push({
          id:
            `unresolved-past-event-${occurrence.id}`,
          type:
            "past-due",
          severity:
            "warning",
          title:
            `${occurrence.event.title} may need an update`,
          description:
            "This scheduled event is in the past but has not been completed or skipped.",
          date:
            occurrence.date,
          eventIds: [
            occurrence.eventId,
          ],
          amount:
            occurrence.event.amount,
          actionLabel:
            getOccurrenceActionLabel(
              occurrence,
            ),
          actionHref:
            getOccurrenceActionHref(
              occurrence,
            ),
        });
      }
    },
  );

  const sortedOccurrences =
    [
      ...occurrences,
    ].sort(
      compareCalendarOccurrences,
    );

  sortedOccurrences.forEach(
    (
      occurrence,
      index,
    ) => {
      if (
        occurrence.event.type !==
        "bill"
      ) {
        return;
      }

      const previousPaycheck =
        sortedOccurrences
          .slice(
            0,
            index,
          )
          .reverse()
          .find(
            (
              candidate,
            ) =>
              candidate.event.type ===
                "paycheck" ||
              candidate.event.type ===
                "income",
          );

      const nextPaycheck =
        sortedOccurrences
          .slice(
            index +
              1,
          )
          .find(
            (
              candidate,
            ) =>
              candidate.event.type ===
                "paycheck" ||
              candidate.event.type ===
                "income",
          );

      if (
        !previousPaycheck &&
        nextPaycheck
      ) {
        conflicts.push({
          id:
            `bill-before-paycheck-${occurrence.id}`,
          type:
            "bill-before-paycheck",
          severity:
            occurrence.event.priority ===
            "critical"
              ? "critical"
              : "warning",
          title:
            `${occurrence.event.title} is due before the next paycheck`,
          description:
            `The bill is due on ${formatShortDate(
              occurrence.date,
            )}, before income scheduled for ${formatShortDate(
              nextPaycheck.date,
            )}.`,
          date:
            occurrence.date,
          eventIds: [
            occurrence.eventId,
            nextPaycheck.eventId,
          ],
          amount:
            occurrence.event.amount,
          actionLabel:
            "Open paycheck planner",
          actionHref:
            "/dashboard/pay-cycles",
        });
      }
    },
  );

  return deduplicateConflicts(
    conflicts,
  ).sort(
    compareCalendarConflicts,
  );
}

