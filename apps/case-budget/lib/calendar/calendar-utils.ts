function deduplicateConflicts(
  conflicts:
    FinancialCalendarConflict[],
) {
  const uniqueConflicts =
    new Map<
      string,
      FinancialCalendarConflict
    >();

  conflicts.forEach(
    (
      conflict,
    ) => {
      if (
        !uniqueConflicts.has(
          conflict.id,
        )
      ) {
        uniqueConflicts.set(
          conflict.id,
          conflict,
        );
      }
    },
  );

  return Array.from(
    uniqueConflicts.values(),
  );
}

function compareCalendarConflicts(
  firstConflict:
    FinancialCalendarConflict,
  secondConflict:
    FinancialCalendarConflict,
) {
  const severityWeights:
    Record<
      FinancialCalendarConflict["severity"],
      number
    > = {
      critical:
        3,
      warning:
        2,
      info:
        1,
    };

  const severityDifference =
    severityWeights[
      secondConflict.severity
    ] -
    severityWeights[
      firstConflict.severity
    ];

  if (
    severityDifference !==
    0
  ) {
    return severityDifference;
  }

  const dateDifference =
    firstConflict.date.localeCompare(
      secondConflict.date,
    );

  if (
    dateDifference !==
    0
  ) {
    return dateDifference;
  }

  return firstConflict.title.localeCompare(
    secondConflict.title,
  );
}

function normalizeCurrency(
  value: number,
) {
  if (
    !Number.isFinite(
      value,
    )
  ) {
    return 0;
  }

  return (
    Math.round(
      value *
        100,
    ) /
    100
  );
}