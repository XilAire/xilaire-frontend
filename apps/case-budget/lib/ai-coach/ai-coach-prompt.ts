export function buildAiCoachContextPrompt({
  summary,
  workspaceName,
  maxInsights =
    DEFAULT_MAX_INSIGHTS,
}: {
  summary:
    AiCoachSummary;

  workspaceName:
    string;

  maxInsights?:
    number;
}) {
  const context =
    summary.context;

  const insights =
    summary.insights.slice(
      0,
      Math.max(
        0,
        maxInsights,
      ),
    );

  return [
    "CASE BUDGET FINANCIAL CONTEXT",
    "",
    `Workspace: ${workspaceName}`,
    `Financial data available: ${summary.hasFinancialData ? "yes" : "no"}`,
    "",
    "CURRENT PERIOD",
    `Start date: ${context.period.startDate}`,
    `End date: ${context.period.endDate}`,
    "",
    "CASH FLOW",
    `Cleared income: ${formatCurrency(context.income)}`,
    `Cleared expenses: ${formatCurrency(context.expenses)}`,
    `Net cash flow: ${formatCurrency(context.cashFlow)}`,
    `Savings rate: ${formatNullablePercentage(context.savingsRate)}`,
    "",
    "BALANCE SHEET",
    `Tracked assets: ${formatCurrency(context.totalAssets)}`,
    `Tracked liabilities: ${formatCurrency(context.totalLiabilities)}`,
    `Tracked net worth: ${formatCurrency(context.netWorth)}`,
    "",
    "EMERGENCY RESERVES",
    `Emergency fund balance: ${formatCurrency(context.emergencyFundBalance)}`,
    `Estimated emergency coverage: ${formatNullableMonths(context.emergencyFundMonths)}`,
    "",
    "DEBT",
    `Active debt balance: ${formatCurrency(context.totalDebt)}`,
    `Tracked minimum debt payments: ${formatCurrency(context.minimumDebtPayments)}`,
    `Active debt count: ${context.debtCount}`,
    "",
    "BILLS",
    `Tracked bill count: ${context.billCount}`,
    `Overdue bills: ${context.overdueBillCount}`,
    `Bills due within seven days: ${context.upcomingBillCount}`,
    "",
    "BUDGET",
    `Assigned amount: ${formatCurrency(context.budgetAssigned)}`,
    `Spent amount: ${formatCurrency(context.budgetSpent)}`,
    `Remaining assigned amount: ${formatCurrency(context.budgetRemaining)}`,
    "",
    "INVESTMENTS",
    `Tracked investment value: ${formatCurrency(context.investmentValue)}`,
    `Tracked investment cost basis: ${formatCurrency(context.investmentCostBasis)}`,
    `Tracked investment gain/loss: ${formatCurrency(context.investmentGainLoss)}`,
    `Investment account count: ${context.investmentAccountCount}`,
    "",
    "DATA COUNTS",
    `Cleared transaction count in period: ${context.transactionCount}`,
    `Account count: ${context.accountCount}`,
    `Savings goal count: ${context.goalCount}`,
    "",
    "CASE COACH SUMMARY",
    `Headline: ${summary.headline}`,
    `Summary: ${summary.summary}`,
    "",
    "DETERMINISTIC CASE INSIGHTS",
    ...formatInsights(
      insights,
    ),
    "",
    "IMPORTANT CONTEXT RULE",
    "",
    "The financial values above are the currently supplied CASE Budget data. Do not invent additional financial facts. If a user asks about information that is not represented here, explain what additional CASE Budget data would be needed.",
  ].join(
    "\n",
  );
}

export function buildAiCoachFinancialContextJson(
  context:
    AiCoachFinancialContext,
) {
  return JSON.stringify(
    context,
    null,
    2,
  );
}

export function buildAiCoachInsightContextJson(
  insights:
    AiCoachInsight[],
) {
  return JSON.stringify(
    insights.map(
      (
        insight,
      ) => ({
        id:
          insight.id,

        type:
          insight.type,

        priority:
          insight.priority,

        tone:
          insight.tone,

        title:
          insight.title,

        description:
          insight.description,

        valueLabel:
          insight.valueLabel,

        action:
          insight.action,
      }),
    ),
    null,
    2,
  );
}

function normalizeConversation(
  conversation:
    AiCoachConversationMessage[],
): AiCoachPromptMessage[] {
  const normalizedMessages:
    AiCoachPromptMessage[] =
    [];

  for (
    const message
    of conversation
  ) {
    const content =
      message.content.trim();

    if (
      !content
    ) {
      continue;
    }

    normalizedMessages.push({
      role:
        message.role,

      content,
    });
  }

  return normalizedMessages;
}

function formatInsights(
  insights:
    AiCoachInsight[],
) {
  if (
    insights.length ===
    0
  ) {
    return [
      "No deterministic CASE coaching insights are currently available.",
    ];
  }

  return insights.map(
    (
      insight,
      index,
    ) =>
      formatInsight({
        insight,

        index,
      }),
  );
}

function formatInsight({
  insight,
  index,
}: {
  insight:
    AiCoachInsight;

  index:
    number;
}) {
  const parts =
    [
      `${index + 1}. ${insight.title}`,
      `   Type: ${insight.type}`,
      `   Priority: ${insight.priority}`,
      `   Tone: ${insight.tone}`,
      `   Description: ${insight.description}`,
    ];

  if (
    insight.valueLabel
  ) {
    parts.push(
      `   Current value: ${insight.valueLabel}`,
    );
  }

  if (
    insight.action
  ) {
    parts.push(
      `   Suggested CASE action: ${insight.action.label} (${insight.action.href})`,
    );
  }

  return parts.join(
    "\n",
  );
}

function normalizeOptionalText(
  value:
    string | null | undefined,
) {
  const normalizedValue =
    value
      ?.trim();

  return (
    normalizedValue ||
    null
  );
}

function formatCurrency(
  value:
    number,
) {
  return new Intl.NumberFormat(
    "en-US",
    {
      style:
        "currency",

      currency:
        "USD",

      minimumFractionDigits:
        2,

      maximumFractionDigits:
        2,
    },
  ).format(
    normalizeFiniteNumber(
      value,
    ),
  );
}

function formatNullablePercentage(
  value:
    number | null,
) {
  if (
    value ===
    null
  ) {
    return "not available";
  }

  return `${new Intl.NumberFormat(
    "en-US",
    {
      minimumFractionDigits:
        1,

      maximumFractionDigits:
        1,
    },
  ).format(
    normalizeFiniteNumber(
      value,
    ),
  )}%`;
}

function formatNullableMonths(
  value:
    number | null,
) {
  if (
    value ===
    null
  ) {
    return "not available";
  }

  const normalizedValue =
    new Intl.NumberFormat(
      "en-US",
      {
        minimumFractionDigits:
          1,

        maximumFractionDigits:
          1,
      },
    ).format(
      normalizeFiniteNumber(
        value,
      ),
    );

  return `${normalizedValue} month${
    Math.abs(
      value -
      1,
    ) <
    0.000001
      ? ""
      : "s"
  }`;
}

function normalizeFiniteNumber(
  value:
    number,
) {
  if (
    !Number.isFinite(
      value,
    )
  ) {
    return 0;
  }

  return value;
}