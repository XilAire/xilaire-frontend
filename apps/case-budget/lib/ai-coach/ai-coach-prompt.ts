import type {
  AiCoachFinancialContext,
  AiCoachInsight,
  AiCoachSummary,
} from "@/lib/ai-coach/ai-coach-service";

export type AiCoachPromptRole =
  | "system"
  | "user"
  | "assistant";

export type AiCoachPromptMessage = {
  role:
    AiCoachPromptRole;

  content:
    string;
};

export type AiCoachConversationMessage = {
  role:
    | "user"
    | "assistant";

  content:
    string;
};

export type BuildAiCoachPromptInput = {
  userMessage:
    string;

  summary:
    AiCoachSummary;

  workspaceName?:
    string | null;

  userFirstName?:
    string | null;

  conversation?:
    AiCoachConversationMessage[];

  maxInsights?:
    number;
};

export type AiCoachPromptBundle = {
  systemPrompt:
    string;

  contextPrompt:
    string;

  messages:
    AiCoachPromptMessage[];
};

const DEFAULT_MAX_INSIGHTS =
  6;

export function buildAiCoachPrompt({
  userMessage,
  summary,
  workspaceName,
  userFirstName,
  conversation = [],
  maxInsights =
    DEFAULT_MAX_INSIGHTS,
}: BuildAiCoachPromptInput): AiCoachPromptBundle {
  const normalizedUserMessage =
    userMessage.trim();

  const normalizedWorkspaceName =
    normalizeOptionalText(
      workspaceName,
    ) ??
    "the active CASE Budget workspace";

  const normalizedFirstName =
    normalizeOptionalText(
      userFirstName,
    );

  const systemPrompt =
    buildAiCoachSystemPrompt({
      workspaceName:
        normalizedWorkspaceName,

      userFirstName:
        normalizedFirstName,
    });

  const contextPrompt =
    buildAiCoachContextPrompt({
      summary,

      workspaceName:
        normalizedWorkspaceName,

      maxInsights,
    });

  const messages:
    AiCoachPromptMessage[] =
    [
      {
        role:
          "system",

        content:
          systemPrompt,
      },

      {
        role:
          "system",

        content:
          contextPrompt,
      },

      ...normalizeConversation(
        conversation,
      ),
    ];

  if (
    normalizedUserMessage
  ) {
    messages.push({
      role:
        "user",

      content:
        normalizedUserMessage,
    });
  }

  return {
    systemPrompt,

    contextPrompt,

    messages,
  };
}

