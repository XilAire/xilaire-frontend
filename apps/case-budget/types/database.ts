  Record<
    string,
    unknown
  >;

export type GenericDatabaseInsert =
  Record<
    string,
    unknown
  >;

export type GenericDatabaseUpdate =
  Record<
    string,
    unknown
  >;

export type GenericDatabaseTable =
  SupabaseTableDefinition<
    GenericDatabaseRow,
    GenericDatabaseInsert,
    GenericDatabaseUpdate
  >;

