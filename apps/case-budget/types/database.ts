/**
 * CASE Budget Supabase database types.
 *
 * File:
 * apps/case-budget/types/database.ts
 *
 * This file is the central TypeScript representation layer for
 * the CASE Budget Supabase/PostgreSQL database.
 *
 * IMPORTANT:
 *
 * CASE Budget already has an existing Supabase database.
 * This file does NOT create, migrate, alter, or otherwise modify
 * that database.
 *
 * It exists only to provide reusable TypeScript types for:
 *
 * - Supabase table rows
 * - insert payloads
 * - update payloads
 * - database functions / RPCs
 * - JSON values
 * - generated database types
 *
 * The current CASE Budget application already communicates with
 * Supabase successfully without passing a Database generic to every
 * Supabase client.
 *
 * This file therefore remains intentionally non-destructive and
 * incrementally typed.
 *
 * Strongly typed definitions are added only for schema objects that
 * have been confirmed against the existing Supabase database.
 */

/**
 * JSON-compatible values supported by PostgreSQL json/jsonb
 * columns and Supabase generated database types.
 */
export type Json =
  | string
  | number
  | boolean
  | null
  | {
      [key: string]:
        Json | undefined;
    }
  | Json[];

/**
 * Foreign-key relationship metadata used by generated Supabase
 * database types.
 */
export type SupabaseRelationship = {
  foreignKeyName:
    string;

  columns:
    string[];

  isOneToOne:
    boolean;

  referencedRelation:
    string;

  referencedColumns:
    string[];
};

/**
 * Common shape used by Supabase-generated table definitions.
 *
 * Row:
 *   The complete record returned by SELECT operations.
 *
 * Insert:
 *   Values accepted when creating a new record.
 *
 * Update:
 *   Values accepted when modifying an existing record.
 *
 * Relationships:
 *   Foreign-key relationship metadata generated by Supabase.
 */
export type SupabaseTableDefinition<
  Row extends Record<
    string,
    unknown
  > = Record<
    string,
    unknown
  >,
  Insert extends Record<
    string,
    unknown
  > = Partial<Row>,
  Update extends Record<
    string,
    unknown
  > = Partial<Insert>,
> = {
  Row:
    Row;

  Insert:
    Insert;

  Update:
    Update;

  Relationships:
    SupabaseRelationship[];
};

/**
 * Generic RPC definition.
 */
export type SupabaseFunctionDefinition<
  Args extends Record<
    string,
    unknown
  > = Record<
    string,
    unknown
  >,
  Returns = Json,
> = {
  Args:
    Args;

  Returns:
    Returns;
};

/**
 * Generic database table fallback.
 *
 * This allows CASE Budget to continue using tables that have not yet
 * been added to the strongly typed schema section below.
 *
 * Once the complete generated Supabase schema is imported, this
 * fallback can be removed.
 */
