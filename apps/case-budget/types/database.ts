/**
 * Current broad application-level database definition.
 *
 * This intentionally remains permissive for tables that have not yet
 * been confirmed and added to this file.
 *
 * The strongly typed workspace definitions above are also exposed
 * through this type.
 *
 * The broad fallback prevents unrelated CASE Budget features from
 * breaking while the complete generated Supabase schema is still
 * being incorporated.
 */
export type Database = {
  public: {
    Tables: {
      workspaces:
        WorkspaceDatabaseTable;

      workspace_members:
        WorkspaceMemberDatabaseTable;

      [tableName: string]:
        GenericDatabaseTable;
    };

    Views:
      Record<
        string,
        {
          Row:
            GenericDatabaseRow;

          Relationships:
            SupabaseRelationship[];
        }
      >;

    Functions: {
      provision_case_budget_user: {
        Args: {
          target_user_id:
            string;
        };

        Returns:
          ProvisionCaseBudgetUserResult;
      };

      sync_case_budget_profile_from_auth: {
        Args: {
          target_user_id:
            string;
        };

        Returns:
          Json;
      };

      [functionName: string]:
        SupabaseFunctionDefinition;
    };

    Enums: {
      workspace_type:
        WorkspaceTypeDatabaseEnum;

      workspace_role:
        WorkspaceRoleDatabaseEnum;

      workspace_membership_status:
        WorkspaceMembershipStatusDatabaseEnum;

      [enumName: string]:
        string;
    };

    CompositeTypes:
      Record<
        string,
        unknown
      >;
  };
};

/**
 * Workspace-only database schema.
 *
 * This exists because Supabase's generic type resolver works best
 * when the table names are concrete literal keys rather than a broad
 * string index signature.
 *
 * Use this schema for clients or operations that specifically work
 * with:
 *
 * - public.workspaces
 * - public.workspace_members
 *
 * This provides strict Insert / Update / Row typing for the Create
 * Workspace flow without forcing the rest of CASE Budget onto an
 * incomplete generated schema.
 */
export type WorkspaceDatabase = {
  public: {
    Tables: {
      workspaces:
        WorkspaceDatabaseTable;

      workspace_members:
        WorkspaceMemberDatabaseTable;
    };

    Views: Record<
      never,
      never
    >;

    Functions: Record<
      never,
      never
    >;

    Enums: {
      workspace_type:
        WorkspaceTypeDatabaseEnum;

      workspace_role:
        WorkspaceRoleDatabaseEnum;

      workspace_membership_status:
        WorkspaceMembershipStatusDatabaseEnum;
    };

    CompositeTypes: Record<
      never,
      never
    >;
  };
};

