import "server-only";
import { createElement } from "react";
import { sendXilAireEmail, type EmailDeliveryResult } from "./send-email";
import { assertXilAirePublicLink, getXilAirePublicUrl } from "./urls";
import { WelcomeEmail } from "@/emails/auth/WelcomeEmail";
import { InviteUserEmail } from "@/emails/auth/InviteUserEmail";
import { InvoiceEmail } from "@/emails/billing/InvoiceEmail";

/** Call these from trusted server-side actions after verifying the underlying event. */
export async function sendWelcomeEmail(input: { to: string; firstName?: string }): Promise<EmailDeliveryResult> {
  const dashboardUrl = getXilAirePublicUrl("/dashboard");
  return sendXilAireEmail({ to: input.to, subject: "Welcome to XilAire Technologies", react: createElement(WelcomeEmail, { firstName: input.firstName, dashboardUrl }), text: `Welcome to XilAire Technologies. Open your workspace: ${dashboardUrl}` });
}

export async function sendInviteUserEmail(input: { to: string; inviteUrl: string; inviterName?: string; organizationName?: string; expiresInHours?: number }): Promise<EmailDeliveryResult> {
  // Invites must be generated by a trusted server-side auth invitation flow.
  const inviteUrl = assertXilAirePublicLink(input.inviteUrl);
  return sendXilAireEmail({ to: input.to, subject: "You're invited to XilAire Technologies", react: createElement(InviteUserEmail, { ...input, inviteUrl }), text: `${input.inviterName || "An administrator"} invited you to XilAire. Accept: ${inviteUrl}` });
}

export async function sendInvoiceEmail(input: { to: string; invoiceNumber: string; customerName?: string; amountDue: string; dueDate?: string; invoiceUrl: string }): Promise<EmailDeliveryResult> {
  // Invoice details/links must be looked up and authorized before calling.
  if (!input.invoiceNumber.trim() || !input.amountDue.trim()) {
    return { success: false, error: "Invoice number and amount due are required." };
  }
  const invoiceUrl = assertXilAirePublicLink(input.invoiceUrl);
  return sendXilAireEmail({ to: input.to, subject: `XilAire invoice ${input.invoiceNumber}`, react: createElement(InvoiceEmail, { ...input, invoiceUrl }), text: `XilAire invoice ${input.invoiceNumber}\nAmount due: ${input.amountDue}${input.dueDate ? `\nDue date: ${input.dueDate}` : ""}\nView securely: ${invoiceUrl}` });
}
